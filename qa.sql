-- Generated from QA.csv using a local neural sentence-transformers model.
-- Model: sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2; normalized embedding dimension: 384.
-- This creates a separate table to preserve any older public.qa TF-IDF data.
create extension if not exists vector with schema extensions;

create table if not exists public.qa_semantic (
    id bigint generated by default as identity primary key,
    question text not null unique,
    category text not null,
    product text not null,
    symptoms text not null,
    answer text not null,
    urgency text not null check (urgency in ('高', '中', '低')),
    content text not null,
    embedding extensions.vector(384) not null,
    created_at timestamptz not null default now()
);

create index if not exists qa_semantic_embedding_hnsw_idx
    on public.qa_semantic using hnsw (embedding extensions.vector_cosine_ops);

create or replace function public.match_qa_semantic (
    query_embedding extensions.vector(384),
    match_count int default 5,
    filter_category text default null
)
returns table (id bigint, question text, category text, product text, symptoms text, answer text, urgency text, content text, similarity float)
language sql stable
as $$
    select q.id, q.question, q.category, q.product, q.symptoms, q.answer, q.urgency, q.content,
           1 - (q.embedding <=> query_embedding) as similarity
    from public.qa_semantic q
    where filter_category is null or q.category = filter_category
    order by q.embedding <=> query_embedding
    limit greatest(match_count, 0);
$$;

-- Allow the app's anon key to call the read-only FAQ search RPC.
-- This policy exposes only the public customer-support FAQ records.
alter table public.qa_semantic enable row level security;
drop policy if exists qa_semantic_public_read on public.qa_semantic;
create policy qa_semantic_public_read
    on public.qa_semantic
    for select
    to anon, authenticated
    using (true);
grant select on public.qa_semantic to anon, authenticated;
grant execute on function public.match_qa_semantic(extensions.vector, integer, text)
    to anon, authenticated;


"""Generate local neural sentence embeddings for QA.csv and export qa.sql."""

import csv
import re
from pathlib import Path

from sentence_transformers import SentenceTransformer


MODEL_NAME = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
EXPECTED_DIMENSION = 384
INPUT_CSV = Path(__file__).with_name("QA.csv")
OUTPUT_SQL = Path(__file__).with_name("qa.sql")
DATA_PARTS_DIR = Path(__file__).with_name("qa_data_parts")
ROWS_PER_PART = 10


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    with INPUT_CSV.open(encoding="utf-8-sig", newline="") as csv_file:
        rows = list(csv.DictReader(csv_file))
    if not rows:
        raise ValueError(f"No records found in {INPUT_CSV}")

    required = {"question", "category", "product", "symptoms", "answer", "urgency"}
    missing = required.difference(rows[0])
    if missing:
        raise ValueError(f"QA.csv is missing columns: {', '.join(sorted(missing))}")

    # Index the question and diagnostic context. Keep the answer as returned data,
    # rather than allowing answer wording to dominate the match for a customer's question.
    contents = [
        f"問題：{row['question']} 分類：{row['category']} 產品：{row['product']} 症狀：{row['symptoms']}"
        for row in rows
    ]
    model = SentenceTransformer(MODEL_NAME, local_files_only=True)
    dimension = model.get_embedding_dimension()
    if dimension != EXPECTED_DIMENSION:
        raise ValueError(f"Expected a {EXPECTED_DIMENSION}-dimension model, got {dimension}")
    embeddings = model.encode(contents, normalize_embeddings=True, show_progress_bar=True)

    lines = [
        "-- Generated from QA.csv using a local neural sentence-transformers model.",
        f"-- Model: {MODEL_NAME}; normalized embedding dimension: {dimension}.",
        "-- This creates a separate table to preserve any older public.qa TF-IDF data.",
        "create extension if not exists vector with schema extensions;",
        "",
        "create table if not exists public.qa_semantic (",
        "    id bigint generated by default as identity primary key,",
        "    question text not null unique,",
        "    category text not null,",
        "    product text not null,",
        "    symptoms text not null,",
        "    answer text not null,",
        "    urgency text not null check (urgency in ('高', '中', '低')),",
        "    content text not null,",
        f"    embedding extensions.vector({dimension}) not null,",
        "    created_at timestamptz not null default now()",
        ");",
        "",
        "create index if not exists qa_semantic_embedding_hnsw_idx",
        "    on public.qa_semantic using hnsw (embedding extensions.vector_cosine_ops);",
        "",
        "create or replace function public.match_qa_semantic (",
        f"    query_embedding extensions.vector({dimension}),",
        "    match_count int default 5,",
        "    filter_category text default null",
        ")",
        "returns table (id bigint, question text, category text, product text, symptoms text, answer text, urgency text, content text, similarity float)",
        "language sql stable",
        "as $$",
        "    select q.id, q.question, q.category, q.product, q.symptoms, q.answer, q.urgency, q.content,",
        "           1 - (q.embedding <=> query_embedding) as similarity",
        "    from public.qa_semantic q",
        "    where filter_category is null or q.category = filter_category",
        "    order by q.embedding <=> query_embedding",
        "    limit greatest(match_count, 0);",
        "$$;",
    ]
    retained_questions = ", ".join(sql_literal(row["question"]) for row in rows)
    lines.extend(
        [
            "",
            "-- Remove records that are no longer present in QA.csv.",
            f"delete from public.qa_semantic where question not in ({retained_questions});",
        ]
    )

    value_rows = []
    for row, content, embedding in zip(rows, contents, embeddings):
        fields = [row[key] for key in ("question", "category", "product", "symptoms", "answer", "urgency")]
        fields.append(content)
        values = [sql_literal(value) for value in fields]
        vector = "[" + ",".join(format(float(value), ".9g") for value in embedding) + "]"
        values.append(sql_literal(vector) + f"::extensions.vector({dimension})")
        value_rows.append("    (" + ", ".join(values) + ")")

    OUTPUT_SQL.write_text("\n".join(lines) + "\n", encoding="utf-8")

    DATA_PARTS_DIR.mkdir(exist_ok=True)
    for old_part in DATA_PARTS_DIR.iterdir():
        if old_part.is_file() and re.fullmatch(r"qa_data_\d{2}\.sql", old_part.name):
            old_part.unlink()
    for part_number, start in enumerate(range(0, len(value_rows), ROWS_PER_PART), start=1):
        batch = value_rows[start : start + ROWS_PER_PART]
        part_lines = [
            f"-- QA semantic data import batch {part_number}",
            "insert into public.qa_semantic (question, category, product, symptoms, answer, urgency, content, embedding)",
            "values",
            ",\n".join(batch),
            "on conflict (question) do update set "
            "category = excluded.category, product = excluded.product, symptoms = excluded.symptoms, "
            "answer = excluded.answer, urgency = excluded.urgency, content = excluded.content, "
            "embedding = excluded.embedding;",
        ]
        part_path = DATA_PARTS_DIR / f"qa_data_{part_number:02d}.sql"
        part_path.write_text("\n".join(part_lines) + "\n", encoding="utf-8")

    part_count = (len(value_rows) + ROWS_PER_PART - 1) // ROWS_PER_PART
    print(f"Created {OUTPUT_SQL.name} and {part_count} data batches: {len(rows)} QA records, {dimension}-dimension neural embeddings")


if __name__ == "__main__":
    main()
